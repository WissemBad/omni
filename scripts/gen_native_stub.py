"""Type stub of the Rust core (``typings/omni_native.pyi``), written from the built module so that pyright knows which
names ``N`` has and with which parameters. Return types stay ``Any``: the docstrings say what each function returns.

    uv run --no-sync python scripts/gen_native_stub.py            # rewrite the stub
    uv run --no-sync python scripts/gen_native_stub.py --check    # exit 1 when the stub is out of date
"""
from __future__ import annotations

import inspect
import keyword
import re
import sys
from pathlib import Path

import omni_native as M

STUB = Path(__file__).resolve().parents[1] / "typings" / "omni_native.pyi"


def params(sig: str | None, drop_self: bool = False) -> str:
    """``(a, b=1, *, c=2)`` from ``__text_signature__`` -> ``a: Any, b: Any = ..., *, c: Any = ...``."""
    if not sig:
        return "*args: Any, **kwargs: Any"
    out = []
    for raw in re.split(r",\s*(?![^()\[\]]*[)\]])", sig.strip()[1:-1]):
        raw = raw.strip()
        if not raw or raw == "/":
            continue
        if raw in ("$self", "self"):
            if not drop_self:
                out.append("self")
            continue
        if raw == "*":
            out.append("*")
            continue
        name, _, default = raw.partition("=")
        name = name.strip()
        if keyword.iskeyword(name):
            name += "_"          # `class` is a Python keyword: callers pass it by position
        if name.startswith("*"):
            out.append(f"{name}: Any")
        else:
            out.append(f"{name}: Any = ..." if default else f"{name}: Any")
    return ", ".join(out) or ""


def doc_line(obj) -> str:
    first = (obj.__doc__ or "").strip().split("\n")[0].replace('"""', "'''")
    return f'    """{first}"""' if first else "    ..."


def render() -> str:
    lines = ['"""Generated by scripts/gen_native_stub.py from the built module: do not edit."""', "from typing import Any", ""]
    for name in sorted(n for n in dir(M) if not n.startswith("_")):
        obj = getattr(M, name)
        if inspect.isclass(obj):
            lines.append(f"class {name}:")
            init = params(getattr(obj, "__text_signature__", None))
            lines.append(f"    def __init__(self, {init}) -> None: ..." if init else "    def __init__(self) -> None: ...")
            for m in sorted(x for x in dir(obj) if not x.startswith("_")):
                attr = getattr(obj, m)
                if callable(attr):
                    sig = params(getattr(attr, "__text_signature__", None), drop_self=True)
                    lines.append(f"    def {m}(self, {sig}) -> Any: ..." if sig else f"    def {m}(self) -> Any: ...")
                else:
                    lines.append(f"    {m}: Any")
            lines.append("")
        elif callable(obj):
            lines.append(f"def {name}({params(getattr(obj, '__text_signature__', None))}) -> Any:")
            lines.append(doc_line(obj))
            lines.append("")
        elif name != "omni_native":
            lines.append(f"{name}: Any")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        raise SystemExit(0 if STUB.exists() and STUB.read_text(encoding="utf-8") == text else 1)
    STUB.parent.mkdir(exist_ok=True)
    STUB.write_text(text, encoding="utf-8", newline="\n")
    print(f"{STUB}: {text.count(chr(10))} lines")
